-- ------------------------------------------------------------
-- 0. 世帯（ふたりの家計）とメンバー
-- ログインは Supabase Auth の Google ログイン。誰と誰がペアかは Google からは分からないので、
-- 「世帯」を作り、招待コードで相手を同じ世帯に入れる。1人が入れる世帯は1つ、1世帯は2人まで。
-- ふたりの記録は household_id、個人の記録は owner（ログインユーザーのID）で持ち主を決める
-- ------------------------------------------------------------
create table if not exists public.households (
  id uuid primary key default gen_random_uuid(),
  invite_code text unique,              -- 招待コード。参加されたら消す（1回だけ使える）
  invite_expires_at timestamp with time zone,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists public.household_members (
  user_id uuid primary key references auth.users (id) on delete cascade, -- 主キーなので1人1世帯
  household_id uuid not null references public.households (id) on delete cascade,
  display_name text not null,
  joined_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create index if not exists household_members_household_id_idx
  on public.household_members (household_id);

-- ログイン中の人の世帯。RLS と列の既定値で使う。
-- household_members の RLS からこの関数を呼ぶので、RLS を通さない security definer にしている
create or replace function public.my_household_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select household_id from public.household_members where user_id = auth.uid()
$$;

-- 世帯を作って自分がメンバーになる
create or replace function public.create_household(display_name text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  new_id uuid;
begin
  if auth.uid() is null then raise exception 'not_signed_in'; end if;
  if exists (select 1 from household_members where user_id = auth.uid()) then raise exception 'already_member'; end if;
  if coalesce(trim(display_name), '') = '' then raise exception 'name_required'; end if;

  insert into households default values returning id into new_id;
  insert into household_members (user_id, household_id, display_name) values (auth.uid(), new_id, trim(display_name));
  return new_id;
end;
$$;

-- 相手に送る招待コードを発行する（24時間有効）。前のコードは使えなくなる
create or replace function public.create_invite()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  hid uuid := public.my_household_id();
  code text;
begin
  if hid is null then raise exception 'no_household'; end if;
  if (select count(*) from household_members where household_id = hid) >= 2 then raise exception 'household_full'; end if;

  -- 推測されないよう、乱数は gen_random_uuid()（暗号論的な乱数）から取る。
  -- 各バイトの下位5ビットはどれも乱数なので、32文字から1文字を偏りなく選べる。
  -- 読み間違えやすい 0/O・1/I は使わない
  select string_agg(substr('ABCDEFGHJKLMNPQRSTUVWXYZ23456789', 1 + get_byte(b, i) % 32, 1), '' order by i)
    into code from (select uuid_send(gen_random_uuid()) as b) r, generate_series(0, 7) i;
  update households set invite_code = code, invite_expires_at = now() + interval '24 hours' where id = hid;
  return code;
end;
$$;

-- 招待コードで相手の世帯に入る。参加されたらコードは消す
create or replace function public.join_household(code text, display_name text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  hid uuid;
begin
  if auth.uid() is null then raise exception 'not_signed_in'; end if;
  if exists (select 1 from household_members where user_id = auth.uid()) then raise exception 'already_member'; end if;
  if coalesce(trim(display_name), '') = '' then raise exception 'name_required'; end if;

  -- 同時に2人が同じコードで入らないよう、世帯の行を押さえてから数える
  select id into hid from households
    where invite_code = upper(trim(code)) and invite_expires_at > now()
    for update;
  if hid is null then raise exception 'invalid_invite'; end if;
  if (select count(*) from household_members where household_id = hid) >= 2 then raise exception 'household_full'; end if;

  insert into household_members (user_id, household_id, display_name) values (auth.uid(), hid, trim(display_name));
  update households set invite_code = null, invite_expires_at = null where id = hid;
  return hid;
end;
$$;

revoke all on function public.create_household(text) from public, anon;
revoke all on function public.create_invite() from public, anon;
revoke all on function public.join_household(text, text) from public, anon;
grant execute on function public.create_household(text) to authenticated;
grant execute on function public.create_invite() to authenticated;
grant execute on function public.join_household(text, text) to authenticated;

